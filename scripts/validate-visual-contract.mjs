assert.match(html, /class=["'][^"']*city-map/);
assert.match(html, /id=["']about["']/);
assert.match(css, /\.course-grid\s*{[\s\S]*display:\s*grid/);
assert.match(css, /\.course-card\s*{[\s\S]*border:/);
