assert.match(css, /\[hidden\]\s*{[^}]*display:\s*none\s*!important/, "Hidden primary views must override component display rules");
assert.match(css, /\.changelog-intro p:not\(\.section-kicker\)\s*{[^}]*margin:\s*\.45rem 0 0/, "Changelog summary needs space below the display heading");
assert.match(css, /--motion-feedback:\s*140ms/, "Control feedback timing must remain explicit");
assert.match(css, /@keyframes github-content-enter/, "Changelog content needs the reference entrance movement");
assert.match(css, /@keyframes github-heading-enter/, "Changelog heading needs the reference reveal");
assert.match(css, /@keyframes github-line-enter/, "Changelog dividers need the reference line reveal");
