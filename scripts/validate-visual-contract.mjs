import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const html = await readFile(new URL("../index.html", import.meta.url), "utf8");
const css = await readFile(new URL("../assets/styles.css", import.meta.url), "utf8");
const app = await readFile(new URL("../assets/app.js", import.meta.url), "utf8");

assert.doesNotMatch(app, /from "\.\/motion\.js"|runViewTransition\(|createContentTransition\(/, "The site must not use the rejected transition orchestration");
assert.match(app, /github-entrance/, "Primary views must replay the GitHub-style entrance sequence");

assert.match(html, /id=["']atlas["']/);
assert.match(html, /id=["']changelog["']/);
assert.match(html, /id=["']journal["']/);
